"""Build docs/EVALUATION_TABLES.md from eval/results/*.json: PYTHONPATH=src uv run python eval/report.py"""
import json
from pathlib import Path

IN_PRICE, OUT_PRICE = 0.30, 2.50  # USD per 1M tokens, Gemini 3.5 Flash-Lite standard tier (ai.google.dev/gemini-api/docs/pricing)
RUNS = [
    ("Dev (synthetic, tuned on)", "dev-tesseract.json", "cached; prompt v2 developed on this set"),
    ("Held-out 1, run 1", "holdout-tesseract-run1.json", "uncached, original code: GATE FAILED (KSF-0093)"),
    ("Held-out 1, run 2", "holdout-tesseract-run2.json", "uncached, fix 1: GATE FAILED (DP-0419)"),
    ("Held-out 1, run 3", "holdout-tesseract-run3.json", "uncached, fix 1: GATE FAILED (DP-0419)"),
    ("Held-out 2, run 1", "holdout2-tesseract-run1.json", "uncached, untouched, fixes 1-2"),
    ("Held-out 2, run 2", "holdout2-tesseract-run2.json", "uncached, untouched, fixes 1-2"),
    ("Held-out 2, run 3", "holdout2-tesseract-run3.json", "uncached, untouched, fixes 1-2"),
    ("Held-out 3, run 1", "holdout3-tesseract-run1.json", "uncached, untouched, fixes 1-4: GATE FAILED (QX-502)"),
    ("Held-out 3, run 2", "holdout3-tesseract-run2.json", "uncached, untouched, fixes 1-4: GATE FAILED (QX-502)"),
    ("Held-out 3, run 3", "holdout3-tesseract-run3.json", "uncached, untouched, fixes 1-4: GATE FAILED (QX-502)"),
    ("Held-out 4, run 1", "holdout4-tesseract-run1.json", "uncached, untouched, fixes 1-5"),
    ("Held-out 4, run 2", "holdout4-tesseract-run2.json", "uncached, untouched, fixes 1-5"),
    ("Held-out 4, run 3", "holdout4-tesseract-run3.json", "uncached, untouched, fixes 1-5"),
    ("Dev rescored", "dev-tesseract-final-rescore.json", "post-hoc: final code"),
    ("Held-out 1 rescored", "holdout-tesseract-run{n}-final-rescore.json", "post-hoc: final code on run 1-3 extractions"),
    ("Held-out 2 rescored", "holdout2-tesseract-run{n}-final-rescore.json", "post-hoc: final code"),
    ("Held-out 3 rescored", "holdout3-tesseract-run{n}-final-rescore.json", "post-hoc: final code"),
    ("Held-out 4 rescored", "holdout4-tesseract-run{n}-final-rescore.json", "post-hoc: final code"),
]


def load(name):
    if "{n}" in name:
        return [json.loads(Path("eval/results", name.format(n=n)).read_text()) for n in (1, 2, 3)]
    return [json.loads(Path("eval/results", name).read_text())]


def row(label, results, note):
    s = [r["summary"] for r in results]
    agg = lambda k: " · ".join(str(x[k]) for x in s)
    cost = [(x["tokens_in_out"][0] * IN_PRICE + x["tokens_in_out"][1] * OUT_PRICE) / 1e6 for x in s]
    lat = [x.get("latency_s_uncached") for x in s]
    lat_txt = " · ".join(f'{l["median"]:.1f}' for l in lat if l) or "cached"
    cost_txt = " · ".join(f"${c:.3f}" for c in cost) if any(l for l in lat) else "-"
    return (f'| {label} | {agg("invoices_scored")} | **{agg("false_confident")}** | {" · ".join(f'{x["computed_correct"]}/{x["computed"]}' for x in s)} '
            f'| {agg("abstention_recall")} | {agg("unnecessary_abstentions")} | {agg("model_request_failures") if "model_request_failures" in s[0] else "-"} '
            f'| {lat_txt} | {cost_txt} | {note} |')


def cases(results, title):
    lines = [f"\n### {title}\n", "| Invoice | Case | Expected | " + " | ".join(f"Run {i+1}" for i in range(len(results))) + " |",
             "|---|---|---|" + "---|" * len(results)]
    for i, case in enumerate(results[0]["cases"]):
        want = case["expected_decision"] or case["expected_reason"] or case["expected"]
        got = []
        for r in results:
            c = r["cases"][i]
            g = c["decision"] or c["reason"] or c["got"]
            got.append(g if c["verdict"] == "ok" else f'{g} ({c["verdict"].replace("_", " ")})')
        lines.append(f'| {case["invoice_no"]} | {case["title"]} | {want} | ' + " | ".join(got) + " |")
    return "\n".join(lines)


def fields(results):
    out = ["\n### Field-level date extraction (summed over runs: correct / wrong / missed / spurious)\n", "| Set | Field | correct | wrong | missed | spurious |", "|---|---|---|---|---|---|"]
    for label, rs in results:
        for name in rs[0]["fields"]:
            t = {k: sum(r["fields"][name].get(k, 0) for r in rs) for k in ("correct", "wrong", "missed", "spurious")}
            out.append(f"| {label} | {name} | {t['correct']} | {t['wrong']} | {t['missed']} | {t['spurious']} |")
    return "\n".join(out)


md = ["<!-- generated by eval/report.py from eval/results; do not edit by hand -->", "# Evaluation tables", "",
      "Values for multiple runs are shown as run1 · run2 · run3. Latency is the median seconds per uncached document. "
      "Cost uses $0.30 / $2.50 per 1M input / output tokens and the token counts the API reported; it is a lower bound if thinking tokens were billed but not reported.", "",
      "| Set | Invoices | Wrong computed | Computed correct | Required abstentions | Unnecessary abstentions | Request failures | Median latency (s) | Cost per run | Notes |",
      "|---|---|---|---|---|---|---|---|---|---|"]
md += [row(label, load(name), note) for label, name, note in RUNS]
h1 = [json.loads(Path(f"eval/results/holdout-tesseract-run{n}.json").read_text()) for n in (1, 2, 3)]
h2 = [json.loads(Path(f"eval/results/holdout2-tesseract-run{n}.json").read_text()) for n in (1, 2, 3)]
h3 = [json.loads(Path(f"eval/results/holdout3-tesseract-run{n}.json").read_text()) for n in (1, 2, 3)]
h4 = [json.loads(Path(f"eval/results/holdout4-tesseract-run{n}.json").read_text()) for n in (1, 2, 3)]
md.append(cases(h1, "Held-out 1 per case (as originally run; runs 2-3 include fix 1)"))
md.append(cases(h2, "Held-out 2 per case (untouched set)"))
md.append(cases(h3, "Held-out 3 per case (untouched, injection-focused)"))
md.append(cases(h4, "Held-out 4 per case (untouched, injection-focused)"))
md.append(fields([("Held-out 1", h1), ("Held-out 2", h2), ("Held-out 3", h3), ("Held-out 4", h4)]))
Path("docs").mkdir(exist_ok=True)
Path("docs/EVALUATION_TABLES.md").write_text("\n".join(md) + "\n")
print("\n".join(md[:16]))
